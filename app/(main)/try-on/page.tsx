"use client";

import { useState, useRef, useCallback } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { Camera, Upload, Trash2, Lock, ArrowRight } from "lucide-react";
import { useRouter } from "next/navigation";
import { DressedFigure } from "@/components/shop/DressedFigure";
import { defaultOutfit } from "@/lib/shop/catalog";
import { loadAvatar, readPortrait, saveAvatar, DEFAULT_AVATAR } from "@/lib/shop/avatar";

type TryOnStep = "upload" | "result";

export default function TryOnPage() {
  const router = useRouter();
  const [step, setStep] = useState<TryOnStep>("upload");
  const [uploadedImage, setUploadedImage] = useState<string | null>(null);
  const [isDragging, setIsDragging] = useState(false);
  const [photoError, setPhotoError] = useState<string | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const handleDragOver = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(true);
  }, []);

  const handleDragLeave = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(false);
  }, []);

  const handleDrop = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(false);

    const file = e.dataTransfer.files[0];
    if (file && file.type.startsWith("image/")) {
      processFile(file);
    }
  }, []);

  const handleFileSelect = useCallback(
    (e: React.ChangeEvent<HTMLInputElement>) => {
      const file = e.target.files?.[0];
      if (file) {
        processFile(file);
      }
    },
    []
  );

  const processFile = async (file: File) => {
    try {
      const photoUrl = await readPortrait(file);
      setUploadedImage(photoUrl);
      setPhotoError(null);
    } catch {
      setPhotoError("That photo couldn't be read. Try another image.");
    }
  };

  const handleStartTryOn = () => {
    if (!uploadedImage) return;
    const existing = loadAvatar() ?? DEFAULT_AVATAR;
    saveAvatar({ ...existing, mode: "photo", photoUrl: uploadedImage });
    setStep("result");
  };

  const handleReset = () => {
    setUploadedImage(null);
    setStep("upload");
  };

  return (
    <div className="min-h-screen bg-brand-50 pt-20">
      {/* Header */}
      <div className="container-wide section-padding py-8">
        <div className="text-center max-w-2xl mx-auto">
          <h1 className="font-display text-4xl md:text-5xl text-brand-900 mb-4">
            Be the Model
          </h1>
          <p className="text-brand-600 text-lg">
            Upload a photo and wear it as the face in the dressing room. Clothes
            are drawn on the figure. Nothing here is generated by a model.
          </p>
        </div>
      </div>

      {/* Main Content */}
      <div className="container-narrow section-padding pb-24">
        <AnimatePresence mode="wait">
          {step === "upload" && (
            <motion.div
              key="upload"
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -20 }}
            >
              {/* Upload Area */}
              <div
                onDragOver={handleDragOver}
                onDragLeave={handleDragLeave}
                onDrop={handleDrop}
                onClick={() => fileInputRef.current?.click()}
                className={`
                  relative border-2 border-dashed rounded-2xl p-12 text-center cursor-pointer transition-all duration-300
                  ${
                    isDragging
                      ? "border-accent-500 bg-accent-50"
                      : uploadedImage
                        ? "border-brand-300 bg-white"
                        : "border-brand-300 bg-brand-100/50 hover:border-brand-400 hover:bg-brand-100"
                  }
                `}
              >
                <input
                  ref={fileInputRef}
                  type="file"
                  accept="image/*"
                  onChange={handleFileSelect}
                  className="hidden"
                />

                {uploadedImage ? (
                  <div className="relative">
                    <img
                      src={uploadedImage}
                      alt="Your uploaded photo"
                      className="max-h-96 mx-auto rounded-lg shadow-lg"
                    />
                    <button
                      onClick={(e) => {
                        e.stopPropagation();
                        handleReset();
                      }}
                      className="absolute top-4 right-4 p-2 bg-white/90 rounded-full shadow-md hover:bg-white transition-colors"
                    >
                      <Trash2 className="w-5 h-5 text-brand-600" />
                    </button>
                  </div>
                ) : (
                  <>
                    <div className="w-20 h-20 mx-auto mb-6 rounded-full bg-brand-200 flex items-center justify-center">
                      <Camera className="w-10 h-10 text-brand-500" />
                    </div>
                    <h3 className="text-xl font-medium text-brand-800 mb-2">
                      Drop your photo here
                    </h3>
                    <p className="text-brand-600 mb-4">
                      or click to browse your files
                    </p>
                    <div className="flex items-center justify-center gap-4">
                      <span className="px-4 py-2 bg-accent-500 text-white rounded-full text-sm">
                        <Upload className="w-4 h-4 inline mr-2" />
                        Upload Photo
                      </span>
                    </div>
                  </>
                )}
              </div>

              {/* Tips */}
              <div className="mt-8 grid grid-cols-1 md:grid-cols-3 gap-6">
                <div className="bg-white rounded-xl p-6 shadow-sm">
                  <div className="w-10 h-10 bg-brand-100 rounded-full flex items-center justify-center mb-4">
                    <span className="text-xl">📸</span>
                  </div>
                  <h4 className="font-medium text-brand-900 mb-2">
                    Front-facing works best
                  </h4>
                  <p className="text-sm text-brand-600">
                    For the most accurate fit preview, use a photo where
                    you&apos;re facing the camera directly.
                  </p>
                </div>
                <div className="bg-white rounded-xl p-6 shadow-sm">
                  <div className="w-10 h-10 bg-brand-100 rounded-full flex items-center justify-center mb-4">
                    <span className="text-xl">💡</span>
                  </div>
                  <h4 className="font-medium text-brand-900 mb-2">
                    Good lighting helps
                  </h4>
                  <p className="text-sm text-brand-600">
                    Natural light or well-lit indoor spaces produce the best
                    results.
                  </p>
                </div>
                <div className="bg-white rounded-xl p-6 shadow-sm">
                  <div className="w-10 h-10 bg-brand-100 rounded-full flex items-center justify-center mb-4">
                    <span className="text-xl">👔</span>
                  </div>
                  <h4 className="font-medium text-brand-900 mb-2">
                    A clear face is enough
                  </h4>
                  <p className="text-sm text-brand-600">
                    We place the photo on the figure&apos;s face. Full-body
                    try-on, where clothes are generated onto you, is still later.
                  </p>
                </div>
              </div>

              {/* Action Button */}
              {photoError && (
                <p className="mt-4 text-center text-sm text-accent-700">{photoError}</p>
              )}

              {uploadedImage && (
                <motion.div
                  initial={{ opacity: 0, y: 20 }}
                  animate={{ opacity: 1, y: 0 }}
                  className="mt-8 text-center"
                >
                  <button
                    onClick={handleStartTryOn}
                    className="inline-flex items-center gap-2 px-8 py-4 bg-accent-500 text-white rounded-full text-lg font-medium hover:bg-accent-600 transition-colors shadow-lg hover:shadow-xl"
                  >
                    <ArrowRight className="w-5 h-5" />
                    Use this photo in the shop
                  </button>
                </motion.div>
              )}

              {/* Privacy Notice */}
              <div className="mt-12 bg-brand-100/50 rounded-xl p-6 flex items-start gap-4">
                <Lock className="w-6 h-6 text-brand-500 flex-shrink-0 mt-0.5" />
                <div>
                  <h4 className="font-medium text-brand-900 mb-1">
                    Your privacy is protected
                  </h4>
                  <p className="text-sm text-brand-600">
                    The photo stays in this browser so the dressing room can use
                    it. It is not uploaded. Clear the site data for this browser
                    and it is gone.
                  </p>
                </div>
              </div>
            </motion.div>
          )}

          {step === "result" && (
            <motion.div
              key="result"
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -20 }}
            >
              <div className="bg-white rounded-2xl shadow-xl overflow-hidden">
                <div className="p-8 text-center bg-gradient-to-b from-brand-100 to-white">
                  <h2 className="font-display text-2xl text-brand-900 mb-2">
                    Your face, on the figure
                  </h2>
                  <p className="text-brand-600">
                    Swap the clothes in the dressing room. The photo does not change them.
                  </p>
                </div>

                <div className="flex justify-center p-8">
                  <DressedFigure
                    outfit={defaultOutfit()}
                    avatar={{
                      ...(loadAvatar() ?? DEFAULT_AVATAR),
                      mode: "photo",
                      photoUrl: uploadedImage ?? undefined,
                    }}
                    className="h-[460px] w-72"
                  />
                </div>

                {/* Actions */}
                <div className="p-8 bg-brand-50 flex flex-col sm:flex-row items-center justify-center gap-4">
                  <button
                    onClick={handleReset}
                    className="px-6 py-3 text-brand-700 hover:text-brand-900 transition-colors"
                  >
                    Try Another Photo
                  </button>
                  <button
                    type="button"
                    onClick={() => router.push("/shop/experience")}
                    className="inline-flex items-center gap-2 px-6 py-3 bg-accent-500 text-white rounded-full hover:bg-accent-600 transition-colors"
                  >
                    Shop this look
                    <ArrowRight className="w-4 h-4" />
                  </button>
                </div>
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </div>
    </div>
  );
}
